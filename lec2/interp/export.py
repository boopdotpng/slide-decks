# writes slides/public/data/resid.json: the residual stream of the 2-layer lookup model on one input,
# per position, after the embedding and after each layer's write. numpy forward pass of ~/code/ml/interp/model.py
#   uv run --with numpy export.py [~/code/ml/interp/checkpoints/attn_only_lookup.safetensors] [a2f5c9d3f]
import json, os, string, struct, sys
import numpy as np

VOCAB = string.ascii_lowercase + string.digits
ckpt = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/code/ml/interp/checkpoints/attn_only_lookup.safetensors")
text = sys.argv[2] if len(sys.argv) > 2 else "a2f5c9d3f"

def load(path):
  b = open(path, "rb").read()
  n = struct.unpack("<Q", b[:8])[0]
  h = json.loads(b[8:8+n])
  return {k: np.frombuffer(b[8+n+v["data_offsets"][0]:8+n+v["data_offsets"][1]], np.float32).reshape(v["shape"])
          for k, v in h.items() if k != "__metadata__"}

W = load(ckpt)
n_layers = len({k.split(".")[1] for k in W if k.startswith("layers.")})
assert not any(".mlp." in k for k in W) and W["layers.0.attn.v_proj.weight"].shape[0] == 32, "one head, no mlp only"

def forward(ids):
  T = len(ids)
  x = W["emb.weight"][ids] + W["pos_emb.weight"][:T]
  stages, writes, attn = [x.copy()], [], []
  for l in range(n_layers):
    q, k, v = (x @ W[f"layers.{l}.attn.{p}_proj.weight"].T for p in "qkv")
    s = q @ k.T / np.sqrt(q.shape[-1]) + np.triu(np.full((T, T), -np.inf), 1)
    p = np.exp(s - s.max(-1, keepdims=True)); p /= p.sum(-1, keepdims=True)
    out = p @ v
    x = x + out
    stages.append(x.copy()); writes.append(out); attn.append(p)
  return stages, writes, attn, x[-1] @ W["unembed.weight"].T

# sanity check against the readme: 100% on random lookups
rng = np.random.default_rng(1)
ok = 0
for _ in range(500):
  keys = rng.permutation(26)[:4]; vals = rng.integers(0, 10, 4); qi = rng.integers(4)
  ids = [t for kv in zip(keys, vals + 26) for t in kv] + [keys[qi]]
  ok += forward(ids)[3].argmax() == vals[qi] + 26
print(f"accuracy on 500 random lookups: {ok / 5:.1f}%")

ids = [VOCAB.index(c) for c in text]
stages, writes, attn, logits = forward(ids)
pr = np.exp(logits - logits.max()); pr /= pr.sum()
r = lambda a: np.round(np.asarray(a, dtype=float), 4).tolist()
out = {
  "text": text, "toks": list(text),
  "tok_emb": r(W["emb.weight"][ids]), "pos_emb": r(W["pos_emb.weight"][:len(ids)]),
  "stages": [r(s) for s in stages],   # residual after embed, after layer 0, after layer 1: (T, 32) each
  "writes": [r(w) for w in writes],   # what each layer's head added: (T, 32)
  "attn": [r(a) for a in attn],       # (T, T) per layer
  "probs": r(pr), "vocab": list(VOCAB),
}
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "slides/public/data/resid.json")
json.dump(out, open(dst, "w"), separators=(",", ":"))
print(f"{text} -> {VOCAB[int(pr.argmax())]} ({pr.max():.1%}); wrote {dst}")

# the lookup model's embedding tables, hardcoded into the slides (36 x 32 and 9 x 32 is small enough)
ts = os.path.join(os.path.dirname(os.path.abspath(__file__)), "slides/src/components/tinyEmbed.ts")
with open(ts, "w") as f:
  f.write("// generated by lec2/interp/export.py from the 2-layer lookup model (attn_only_lookup.safetensors). don't edit\n")
  f.write(f"export const VOCAB = {json.dumps(VOCAB)};\n")
  f.write(f"/** token embedding, one row per token in VOCAB: (36, 32) */\nexport const EMB: number[][] = {json.dumps(np.round(W['emb.weight'].astype(float), 3).tolist())};\n")
  f.write(f"/** position embedding, one row per position: (9, 32) */\nexport const POS: number[][] = {json.dumps(np.round(W['pos_emb.weight'].astype(float), 3).tolist())};\n")
print(f"wrote {ts}")
